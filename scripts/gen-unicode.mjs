// Regenerate pinned Unicode 17 tables and the official normalization corpus.
import { mkdir, readFile, writeFile } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { join, resolve } from 'node:path';
import { createHash } from 'node:crypto';
const version = '17.0.0';
const cache = join(tmpdir(), `toil-unicode-${version}`);
await mkdir(cache, {recursive:true});
const names = ['UnicodeData.txt','DerivedNormalizationProps.txt','PropList.txt','NormalizationTest.txt','DerivedCoreProperties.txt'];
const expectedHashes = {
  "DerivedCoreProperties.txt": "24c7fed1195c482faaefd5c1e7eb821c5ee1fb6de07ecdbaa64b56a99da22c08",
  "UnicodeData.txt": "2e1efc1dcb59c575eedf5ccae60f95229f706ee6d031835247d843c11d96470c",
  "DerivedNormalizationProps.txt": "71fd6a206a2c0cdd41feb6b7f656aa31091db45e9cedc926985d718397f9e488",
  "PropList.txt": "130dcddcaadaf071008bdfce1e7743e04fdfbc910886f017d9f9ac931d8c64dd",
  "NormalizationTest.txt": "5019ffd530751a741900c849c0e010332f142a3612234639bd200b82138a87db"
};
const inputs = await Promise.all(names.map(async name => {
  const path=join(cache,name);
  let data;
  try { data=await readFile(path,'utf8'); } catch {
    const response=await fetch(`https://www.unicode.org/Public/${version}/ucd/${name}`);
    if(!response.ok) throw new Error(`${name}: HTTP ${response.status}`);
    data=await response.text(); await writeFile(path,data);
  }
  const digest=createHash('sha256').update(data).digest('hex');
  if(digest!==expectedHashes[name]) throw new Error(`Pinned Unicode checksum mismatch: ${name}`);
  return data;
}));
const categories=['Cn','Lu','Ll','Lt','Lm','Lo','Mn','Mc','Me','Nd','Nl','No','Pc','Pd','Ps','Pe','Pi','Pf','Po','Sm','Sc','Sk','So','Zs','Zl','Zp','Cc','Cf','Cs','Co'];
const cat=new Uint8Array(0x110000), ccc=new Uint8Array(0x110000), decomposition=new Map();
const lowercase=new Int32Array(0x110000);
let first=-1;
for(const line of inputs[0].trim().split('\n')) {
  const f=line.trim().split(';'), cp=parseInt(f[0],16), category=categories.indexOf(f[2]);
  if(category<0) throw new Error(`Unknown category ${f[2]}`);
  if(f[1].endsWith(', First>')) { first=cp;continue; }
  const from=f[1].endsWith(', Last>') ? first : cp;
  if(from<0) throw new Error('Invalid Unicode range');
  cat.fill(category,from,cp+1); ccc.fill(Number(f[3]),from,cp+1);
  if(f[13]) lowercase[cp]=parseInt(f[13],16)-cp;
  if(f[5]) {
    const parts=f[5].split(' '), compat=parts[0].startsWith('<');
    decomposition.set(cp,{compat,seq:(compat?parts.slice(1):parts).map(x=>parseInt(x,16))});
  }
}
const exclusions=new Set(), whitespace=[];
for(const line of inputs[1].split('\n')) {
  const f=line.split('#')[0].trim().split(';').map(x=>x.trim());
  if(f[1]!=='Full_Composition_Exclusion') continue;
  const r=f[0].split('..').map(x=>parseInt(x,16));
  for(let cp=r[0];cp<=(r[1]??r[0]);cp++) exclusions.add(cp);
}
for(const line of inputs[2].split('\n')) {
  const f=line.split('#')[0].trim().split(';').map(x=>x.trim());
  if(f[1]!=='White_Space') continue;
  const r=f[0].split('..').map(x=>parseInt(x,16));whitespace.push(r[0],r[1]??r[0],1);
}
const cased=new Uint8Array(0x110000), caseIgnorable=new Uint8Array(0x110000);
for(const line of inputs[4].split('\n')) {
  const f=line.split('#')[0].trim().split(';').map(x=>x.trim());
  const target=f[1]==='Cased'?cased:f[1]==='Case_Ignorable'?caseIgnorable:null;
  if(!target) continue;
  const r=f[0].split('..').map(x=>parseInt(x,16));
  target.fill(1,r[0],(r[1]??r[0])+1);
}
function ranges(values, skipZero) {
  const result=[];
  for(let start=0;start<values.length;) {
    let end=start+1;while(end<values.length && values[end]===values[start]) end++;
    if(!skipZero || values[start]!==0) result.push(start,end-1,values[start]);
    start=end;
  }
  return result;
}
const descriptors=[], points=[], composition=[];
for(const [cp,{compat,seq}] of decomposition) {
  descriptors.push(cp,points.length,seq.length,Number(compat));points.push(...seq);
  if(!compat && seq.length===2 && !exclusions.has(cp)) composition.push([seq[0],seq[1],cp]);
}
composition.sort((a,b)=>a[0]-b[0]||a[1]-b[1]);
let output=`// Generated by scripts/gen-unicode.mjs from Unicode ${version}.\n// Unicode data license: unicode-LICENSE.txt. Do not edit.\n`;
for(let i=0;i<names.length;i++) output+=`// ${names[i]} SHA256 ${createHash('sha256').update(inputs[i]).digest('hex')}\n`;
for(const [name,values,stride] of [['CATEGORIES',ranges(cat,false),3],['COMBINING',ranges(ccc,true),3],
  ['LOWERCASE',ranges(lowercase,true),3],['CASED',ranges(cased,true),3],['CASE_IGNORABLE',ranges(caseIgnorable,true),3],['WHITESPACE',whitespace,3],['DECOMPOSITIONS',descriptors,4],['DECOMPOSED_POINTS',points,1],['COMPOSITIONS',composition.flat(),3]]) {
  output+=`\n@lazy @inline export const ${name}_COUNT:i32=${values.length/stride};\n@lazy @inline export const ${name}:usize=memory.data<i32>([\n`;
  for(let i=0;i<values.length;i+=16) output+='  '+values.slice(i,i+16).join(',')+',\n';
  output+=']);\n';
}
output+=`\n@lazy export const CATEGORY_NAMES:StaticArray<string>=[${categories.map(x=>JSON.stringify(x)).join(',')}];\n`;
await writeFile(resolve('std/assembly/util/unicode-data.ts'),output);
await writeFile(resolve('tests/unicode/NormalizationTest.txt'),inputs[3]);
await writeFile(resolve('tests/unicode/lowercase.json'),JSON.stringify(Array.from(lowercase.entries()).filter(([,delta])=>delta!==0).map(([cp,delta])=>[cp,cp+delta]))+'\n');
const license=await fetch('https://www.unicode.org/license.txt');
if(!license.ok) throw new Error('Cannot download Unicode license');
await writeFile(resolve('std/assembly/util/unicode-LICENSE.txt'),await license.text());
console.log(`Generated Unicode ${version}: ${descriptors.length/4} decompositions, ${composition.length} compositions`);
