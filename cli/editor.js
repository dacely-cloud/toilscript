import { path } from "../util/node.js";

/** Plain declarations for editors whose TypeScript engine cannot load TS plugins.
 * Read the compiler's parsed declarations, rather than guessing decorators with
 * a regex or giving every Object an encode method. No executable code is emitted.
 */
export function buildEditorTypes(program, compiler, outputFile, baseDir) {
  const { NodeKind, CommonFlags, DecoratorKind } = compiler;
  const outputDir = path.dirname(path.resolve(baseDir, outputFile));
  const blocks = [];
  const userTypes = [];
  for (const source of program.sources) {
    if (source.isLibrary || source.normalizedPath.endsWith(".d.ts")) continue;
    const original = source.statements.filter(node => node.range.source === source);
    const isModule = original.some(node =>
      node.kind === NodeKind.Import || node.kind === NodeKind.Export ||
      (node.flags & CommonFlags.Export) !== 0
    );
    let specifier = path.relative(outputDir, path.resolve(baseDir, source.normalizedPath))
      .replace(/\\/g, "/").replace(/\.ts$/, "");
    if (!specifier.startsWith(".")) specifier = "./" + specifier;
    const declarations = [];
    for (const node of original) {
      if (node.kind !== NodeKind.ClassDeclaration) continue;
      // Module augmentations merge named exports. A private module class must be
      // exported to make it augmentable without rewriting the user's source.
      if (isModule && !(node.flags & CommonFlags.Export)) continue;
      const decorators = node.decorators || [];
      const isUser = decorators.some(d => d.decoratorKind === DecoratorKind.User);
      const isData = isUser || decorators.some(d => d.decoratorKind === DecoratorKind.Data);
      const name = node.name.text;
      if (isData) {
        declarations.push(
          `  interface ${name} {\n` +
          "    encode(): Uint8Array;\n" +
          "    encodeInto(writer: DataWriter): void;\n" +
          "    encodedSize(): i32;\n" +
          "    decodeInto(bytes: Uint8Array): void;\n" +
          "    decodeIntoVersioned(bytes: Uint8Array, version: i64): void;\n" +
          "    toJSON(): JSON;\n" +
          "  }\n" +
          `  namespace ${name} {\n` +
          `    function decode(bytes: Uint8Array): ${name};\n` +
          `    function decodeFrom(reader: DataReader): ${name};\n` +
          `    function fromJSON(value: JSON): ${name};\n` +
          "    function dataId(): u32;\n" +
          "  }"
        );
        if (isUser && isModule) userTypes.push({ name, specifier });
        if (isUser && !isModule) declarations.push(`  interface __ToilAuthUser extends ${name} {}`);
      }
    }
    if (declarations.length) blocks.push(
      (isModule ? `declare module ${JSON.stringify(specifier)}` : "declare global") +
      " {\n" + declarations.join("\n") + "\n}"
    );
  }
  const users = userTypes.map(({ name, specifier }, index) =>
    `import type { ${name} as __ToilEditorUser${index} } from ${JSON.stringify(specifier)};\n` +
    `declare global { interface __ToilAuthUser extends __ToilEditorUser${index} {} }`
  );
  return "// Generated by toilscript --editorTypes. Do not edit.\n" +
    "// Include this file in your server tsconfig.json (TypeScript 7 / WebStorm).\n" +
    "export {};\n\n" + blocks.concat(users).join("\n\n") + "\n";
}
